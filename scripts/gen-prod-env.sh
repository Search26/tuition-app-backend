#!/usr/bin/env bash
# Write .env.prod for a domain, with a fresh random value for every password and secret.
# Usage: scripts/gen-prod-env.sh api.yourdomain.com
# Refuses to overwrite an existing .env.prod: rotating secrets is a deliberate, documented step.
set -euo pipefail
cd "$(dirname "$0")/.."

domain=${1:?usage: scripts/gen-prod-env.sh <domain>}
out=${ENV_OUT:-.env.prod}
if [ -e "$out" ]; then
  echo "$out already exists; not overwriting it (see docs/deploy.md, Rotating secrets)" >&2
  exit 1
fi

# Hex: safe inside URLs (DATABASE_URL, REDIS_URL) without escaping.
secret() { openssl rand -hex 32; }
pg_password=$(secret)
redis_password=$(secret)

umask 077
cat > "$out" <<ENV
# Generated by scripts/gen-prod-env.sh on $(date -u +%Y-%m-%d). Keep it on the VPS only.
APP_ENV=prod
LOG_FORMAT=json
LOG_LEVEL=INFO
DOMAIN=$domain

POSTGRES_USER=tuition
POSTGRES_PASSWORD=$pg_password
POSTGRES_DB=tuition
DATABASE_URL=postgresql+asyncpg://tuition:$pg_password@postgres:5432/tuition

REDIS_PASSWORD=$redis_password
REDIS_URL=redis://:$redis_password@redis:6379/0

MINIO_ENDPOINT=minio:9000
MINIO_ACCESS_KEY=tuition-$(openssl rand -hex 6)
MINIO_SECRET_KEY=$(secret)
MINIO_SECURE=false
MINIO_REGION=us-east-1
MINIO_BUCKET=tuition-media
# Admin uploads go through an SSH tunnel to the VPS's loopback MinIO (docs/deploy.md).
MINIO_PUBLIC_ENDPOINT=localhost:9000
MINIO_PUBLIC_SECURE=false

JWT_SECRET=$(secret)
MEDIA_SIGNING_SECRET=$(secret)
MEDIA_BASE_URL=https://$domain/media
CORS_ORIGINS=

BACKUP_DIR=/var/backups/tuition
BACKUP_KEEP=14
# An rclone remote for an off-VPS copy, defined in RCLONE_CONFIG_FILE, e.g. b2:my-bucket/tuition.
BACKUP_REMOTE=
RCLONE_CONFIG_FILE=./deploy/rclone.conf
ENV

# compose.prod.yml mounts this file into the rclone container; it must exist, even empty.
[ -e deploy/rclone.conf ] || : > deploy/rclone.conf
chmod 600 deploy/rclone.conf
echo "Wrote $out for $domain"
