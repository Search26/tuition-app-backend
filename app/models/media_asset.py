import enum
import uuid
from datetime import datetime

from sqlalchemy import (
    BigInteger,
    CheckConstraint,
    DateTime,
    Enum,
    ForeignKey,
    Index,
    String,
    Text,
    func,
)
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base


class MediaAssetStatus(enum.StrEnum):
    # Row exists, presigned URL issued, upload not confirmed yet.
    PENDING = "pending"
    UPLOADED = "uploaded"
    # Owned by the Sprint 4 transcode worker.
    PROCESSING = "processing"
    READY = "ready"
    FAILED = "failed"


class MediaAsset(Base):
    """A lesson's source video in MinIO."""

    __tablename__ = "media_assets"
    __table_args__ = (
        Index("ix_media_assets_lesson_id_created_at", "lesson_id", "created_at"),
        CheckConstraint("size_bytes >= 0", name="size_non_negative"),
    )

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid.uuid4)
    lesson_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("lessons.id", ondelete="CASCADE"))
    # Generated by the server: original/{course_id}/{lesson_id}/{id}.{ext}
    original_key: Mapped[str] = mapped_column(Text, unique=True)
    content_type: Mapped[str] = mapped_column(String(100))
    # Real size from MinIO, set at upload-complete.
    size_bytes: Mapped[int | None] = mapped_column(BigInteger)
    status: Mapped[MediaAssetStatus] = mapped_column(
        Enum(
            MediaAssetStatus,
            name="media_asset_status",
            values_callable=lambda e: [m.value for m in e],
        ),
        server_default=MediaAssetStatus.PENDING.value,
        default=MediaAssetStatus.PENDING,
    )
    error_msg: Mapped[str | None] = mapped_column(Text)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now()
    )
